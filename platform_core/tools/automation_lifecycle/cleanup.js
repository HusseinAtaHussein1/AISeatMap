// Cleanup — Step 4 of the Automation Asset Lifecycle (pipeline.md §12.5). Deletes ONLY files the
// Merge Plan actually accounted for — never a blind recursive delete, so nothing can vanish without a
// corresponding line in the Merge Summary.
//
// TWO SCOPES, and the caller must choose (pipeline.md §12.5):
//
//   'build-only' (the default, and correct for a Module Automation Project)
//       Deletes only build/IDE output already classified as Discarded Untracked. The project's
//       SOURCE stays, because a module project is the module's durable automation home — Stage 5A
//       executes it and Stage 5H heals it next time. Deleting it would recreate exactly the problem
//       the module workspace was introduced to solve.
//
//   'all-accounted' (the pre-2026-07-29 behaviour, for a temporary working copy)
//       Deletes every merged path as well. Only correct for a location that is meant to disappear
//       after the merge. The run working copy this served is removed (pipeline.md §12.1), so this
//       scope is retained for pre-migration callers rather than as the recommended path.
//
// The default is the safe one on purpose: a caller that forgets to pass a scope keeps a runnable
// project, and the failure mode is a stale build directory rather than a deleted test suite.

const fs = require('fs');
const path = require('path');

const CLEANUP_SCOPES = ['build-only', 'all-accounted'];
const DEFAULT_CLEANUP_SCOPE = 'build-only';

class CleanupScopeError extends Error {
  constructor(message) {
    super(message);
    this.name = 'CleanupScopeError';
  }
}

/**
 * Every relative path a cleanup pass at `scope` is allowed to delete.
 *
 * @param {object} plan - the Merge Plan (or the subset actually applied, if some files were held
 *   back for an unresolved conflict — those must be excluded from the caller's `plan` so they stay
 *   in place until a follow-up merge resolves them)
 * @param {string} [scope] - one of CLEANUP_SCOPES
 * @returns {string[]}
 */
function accountedForPaths(plan, scope = 'all-accounted') {
  if (!CLEANUP_SCOPES.includes(scope)) {
    throw new CleanupScopeError(
      `Unknown cleanup scope "${scope}". Expected one of: ${CLEANUP_SCOPES.join(', ')}.`
    );
  }
  // Discarded build/IDE output is deletable under BOTH scopes: it is regenerated by the next build,
  // and it is the only thing 'build-only' touches.
  if (scope === 'build-only') return [...plan.discardedIgnored];

  return [
    ...plan.added,
    ...plan.modified,
    ...plan.deleted,
    ...plan.renamed.map((r) => r.from),
    ...plan.discardedIgnored,
  ];
}

/**
 * @param {string} packageAbsPath - the module automation project, or a legacy run working copy
 * @param {object} plan
 * @param {{fs?: object, apply?: boolean, scope?: string}} [deps]
 * @returns {{scope: string, wouldDelete: string[], deleted: string[]}}
 */
function cleanupPackage(packageAbsPath, plan, deps = {}) {
  const fsImpl = deps.fs || fs;
  const apply = Boolean(deps.apply);
  const scope = deps.scope || DEFAULT_CLEANUP_SCOPE;
  const candidates = accountedForPaths(plan, scope);
  const workingCopyAbsPath = packageAbsPath;

  if (!apply) {
    return { scope, wouldDelete: candidates, deleted: [] };
  }

  const deleted = [];
  for (const rel of candidates) {
    const absPath = path.join(workingCopyAbsPath, rel);
    if (fsImpl.existsSync(absPath)) {
      fsImpl.rmSync(absPath, { recursive: true, force: true });
      deleted.push(rel);
    }
  }

  // Remove now-empty directories left behind, deepest first — but only within the package itself,
  // never anything above it. Under 'build-only' this prunes an emptied `target/` and stops there.
  removeEmptyDirs(workingCopyAbsPath, fsImpl);

  return { scope, wouldDelete: candidates, deleted };
}

/**
 * The pre-2026-07-29 entry point, kept so existing callers and in-flight runs keep working.
 *
 * It defaults to `'all-accounted'` rather than to the new safe default, because that is what its
 * existing callers meant when they called it: silently narrowing their behaviour would leave merged
 * source behind in a location they expect to be emptied. New callers use cleanupPackage().
 *
 * @deprecated Use cleanupPackage() with an explicit `scope`.
 */
function cleanupRunPackage(workingCopyAbsPath, plan, deps = {}) {
  return cleanupPackage(workingCopyAbsPath, plan, { scope: 'all-accounted', ...deps });
}

/**
 * @param {string} dirAbsPath
 * @param {object} fsImpl
 * @returns {boolean} true if `dirAbsPath` itself is now empty and was removed
 */
function removeEmptyDirs(dirAbsPath, fsImpl) {
  let entries;
  try {
    entries = fsImpl.readdirSync(dirAbsPath, { withFileTypes: true });
  } catch {
    return false;
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      removeEmptyDirs(path.join(dirAbsPath, entry.name), fsImpl);
    }
  }
  const remaining = fsImpl.readdirSync(dirAbsPath);
  if (remaining.length === 0) {
    fsImpl.rmdirSync(dirAbsPath);
    return true;
  }
  return false;
}

module.exports = {
  CLEANUP_SCOPES,
  DEFAULT_CLEANUP_SCOPE,
  CleanupScopeError,
  accountedForPaths,
  cleanupPackage,
  cleanupRunPackage,
};
