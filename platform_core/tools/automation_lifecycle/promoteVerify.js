// Promotion Verification — proves the Workspace Automation Baseline holds a complete, byte-identical
// copy of a module's automation BEFORE that module's working copy is retired.
// See workflows_and_pipelines/pipeline/pipeline.md §12.5.
//
// This is the difference between a promotion and a deletion. Retiring a module directory on the
// strength of "the merge reported success" trusts a summary; this re-reads both trees from disk and
// compares content hashes, so the proof is independent of the thing being proved.
//
// WHAT IS COMPARED, and what deliberately is not:
//   compared     — every non-ignored file in the module project. These are the source files the
//                  suite needs to run, and each must exist in the baseline with an identical hash.
//   not compared — files git ignores (target/, allure-results/, .idea/, report output). They are
//                  regenerated by the next build, they are never merged (§12.4 step 5 classifies
//                  them as Discarded Untracked), and requiring them in the baseline would fail every
//                  verification for the wrong reason.
//   not required — baseline files with no module counterpart. The baseline is a WHOLE-PROJECT suite
//                  and legitimately holds other modules' code plus shared assets. Their absence from
//                  the module is expected; it is reported as `baselineOnly` for the record, never as
//                  a failure.
//
// The verification passes only when `missing` and `differing` are both empty. There is no threshold
// and no "close enough": one missing test class is one test that silently stops running.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const { hashContent, walkFiles } = require('./hashUtils');
const { discoverRepo, isIgnored } = require('./gitUtils');

function toPosix(p) {
  return String(p).split(path.sep).join('/');
}

/**
 * relPath -> sha256 for every non-ignored file under `dirAbsPath`.
 * @param {string} dirAbsPath
 * @param {object|null} repo
 * @param {{fs?: object, execFileSync?: Function}} deps
 * @returns {{files: Map<string,string>, ignored: string[]}}
 */
function hashTree(dirAbsPath, repo, deps = {}) {
  const fsImpl = deps.fs || fs;
  const exec = deps.execFileSync || execFileSync;
  const files = new Map();
  const ignored = [];
  for (const abs of walkFiles(dirAbsPath, { fs: fsImpl })) {
    const rel = toPosix(path.relative(dirAbsPath, abs));
    if (repo && isIgnored(repo, abs, { execFileSync: exec })) {
      ignored.push(rel);
      continue;
    }
    files.set(rel, hashContent(fsImpl.readFileSync(abs)));
  }
  return { files, ignored };
}

/**
 * Verifies that `baselineAbsPath` fully contains `moduleAbsPath`'s automation.
 *
 * @param {string} baselineAbsPath
 * @param {string} moduleAbsPath
 * @param {{fs?: object, execFileSync?: Function, repo?: object}} [deps]
 * @returns {{passed: boolean, verifiedCount: number, missing: string[],
 *            differing: Array<{path: string, moduleHash: string, baselineHash: string}>,
 *            baselineOnly: string[], ignoredInModule: string[], modulePath: string,
 *            baselinePath: string, reason: string}}
 */
function verifyPromotion(baselineAbsPath, moduleAbsPath, deps = {}) {
  const fsImpl = deps.fs || fs;
  const exec = deps.execFileSync || execFileSync;

  if (!fsImpl.existsSync(moduleAbsPath)) {
    return {
      passed: false,
      verifiedCount: 0,
      missing: [],
      differing: [],
      baselineOnly: [],
      ignoredInModule: [],
      modulePath: toPosix(moduleAbsPath),
      baselinePath: toPosix(baselineAbsPath),
      reason: `Module project not found at ${toPosix(moduleAbsPath)} — nothing to verify. If it was ` +
        'already retired, the promotion record is the authority, not a re-run of this check.',
    };
  }
  if (!fsImpl.existsSync(baselineAbsPath)) {
    return {
      passed: false,
      verifiedCount: 0,
      missing: [],
      differing: [],
      baselineOnly: [],
      ignoredInModule: [],
      modulePath: toPosix(moduleAbsPath),
      baselinePath: toPosix(baselineAbsPath),
      reason: `Baseline not found at ${toPosix(baselineAbsPath)}. Retiring the module copy now would ` +
        'delete the only copy of this automation.',
    };
  }

  // An EXPLICIT `repo: null` means "compare every file, consult no git" — checked with `in` rather
  // than truthiness so a caller that has already decided there is no repository does not trigger a
  // discovery shell-out (and, in a temp directory, a stream of `not a git repository` noise).
  const repo = 'repo' in deps ? deps.repo : discoverRepo(baselineAbsPath, { execFileSync: exec });
  const module = hashTree(moduleAbsPath, repo, { fs: fsImpl, execFileSync: exec });
  const baseline = hashTree(baselineAbsPath, repo, { fs: fsImpl, execFileSync: exec });

  const missing = [];
  const differing = [];
  for (const [rel, hash] of module.files) {
    const baselineHash = baseline.files.get(rel);
    if (baselineHash === undefined) {
      missing.push(rel);
    } else if (baselineHash !== hash) {
      differing.push({ path: rel, moduleHash: hash, baselineHash });
    }
  }

  const baselineOnly = [...baseline.files.keys()].filter((rel) => !module.files.has(rel));
  const passed = missing.length === 0 && differing.length === 0;

  return {
    passed,
    verifiedCount: module.files.size,
    missing,
    differing,
    baselineOnly,
    ignoredInModule: module.ignored,
    modulePath: toPosix(moduleAbsPath),
    baselinePath: toPosix(baselineAbsPath),
    reason: passed
      ? `All ${module.files.size} module file(s) present in the baseline with identical content.`
      : `${missing.length} missing and ${differing.length} differing file(s) — the baseline is NOT a ` +
        'complete copy, so the module project must not be retired.',
  };
}

/**
 * Renders the verification as the Markdown block that goes into automation_promotion.md. Kept beside
 * the check itself so the record can never drift from what was actually verified.
 * @param {object} report - a verifyPromotion() result
 * @returns {string}
 */
function renderVerificationReport(report) {
  const list = (items) => (items.length ? items.map((i) => `- \`${i}\``).join('\n') : '- (none)');
  return `### Promotion Verification

| Field | Value |
|---|---|
| Result | ${report.passed ? '**PASSED**' : '**FAILED**'} |
| Module project | \`${report.modulePath}\` |
| Baseline | \`${report.baselinePath}\` |
| Files verified identical | ${report.verifiedCount} |
| Missing from baseline | ${report.missing.length} |
| Differing content | ${report.differing.length} |
| Baseline-only files (other modules + shared) | ${report.baselineOnly.length} |
| Ignored in module, not compared (build/IDE output) | ${report.ignoredInModule.length} |

${report.reason}

**Missing from baseline**
${list(report.missing)}

**Differing content**
${list(report.differing.map((d) => `${d.path} (module ${d.moduleHash.slice(0, 12)} vs baseline ${d.baselineHash.slice(0, 12)})`))}
`;
}

module.exports = { verifyPromotion, renderVerificationReport, hashTree };
