// Module Scaffold — creates a Module Workspace's folder skeleton.
//
// See workflows_and_pipelines/pipeline/module_architecture.md §5.1.
//
// Scaffolding is deliberately SEPARATE from registration (moduleRegistry.js). A module proposed by
// Stage 1 is registered but NOT scaffolded, because a folder on disk reads as "this module exists"
// and no module exists until a human approves the decomposition at Stage 1's gate (§6.4 #4).
//
// Only two of the five stage folders are created up front. The rest are created by the stage that
// writes them, which is the same rule pipeline.md §7 already applies to a run's stage folders: a
// folder's ABSENCE is the record that the stage did not run. Pre-creating all five would erase that
// signal and make every module look like it reached Stage 5H.

const fs = require('fs');
const path = require('path');

const { MODULE_STAGES, writeJsonAtomic, readRegistry, findModule } = require('./moduleRegistry');
const { assertValidModuleSlug } = require('./moduleSlug');

class ModuleScaffoldError extends Error {
  constructor(message) {
    super(message);
    this.name = 'ModuleScaffoldError';
  }
}

/**
 * Folders every scaffolded module gets immediately. `context/` because Stage 1 writes into it as
 * soon as the module is approved, and `discovery/` because Stage 2 follows directly. The remaining
 * three — test_design/, automation/, healing/ — are created on first write by their own stage.
 */
const EAGER_STAGE_FOLDERS = ['context', 'discovery'];

/**
 * Computes what scaffolding WOULD do, without writing. The plan/apply split mirrors
 * automation_lifecycle's mergePlan/mergeApply and run_manager's planRefinement/writeLineage — a
 * caller can always show the user what is about to happen before it happens.
 *
 * @param {string} modulesDir
 * @param {string} slug
 * @returns {{slug: string, moduleDir: string, exists: boolean, createDirs: string[], createFiles: string[]}}
 */
function planScaffold(modulesDir, slug) {
  assertValidModuleSlug(slug);
  const moduleDir = path.join(modulesDir, slug);
  const exists = fs.existsSync(moduleDir);

  const createDirs = [];
  if (!exists) createDirs.push(moduleDir);
  for (const stage of EAGER_STAGE_FOLDERS) {
    const dir = path.join(moduleDir, stage);
    if (!fs.existsSync(dir)) createDirs.push(dir);
  }
  const findingsDir = path.join(moduleDir, 'discovery', 'findings');
  if (!fs.existsSync(findingsDir)) createDirs.push(findingsDir);
  const evidenceDir = path.join(moduleDir, 'discovery', 'evidence');
  if (!fs.existsSync(evidenceDir)) createDirs.push(evidenceDir);

  const createFiles = [];
  for (const file of ['module.json', 'README.md']) {
    if (!fs.existsSync(path.join(moduleDir, file))) {
      createFiles.push(path.join(moduleDir, file));
    }
  }

  return { slug, moduleDir, exists, createDirs, createFiles };
}

/**
 * Creates a module's folder skeleton and its module.json.
 *
 * Idempotent: an existing module is left exactly as it is, and existing files are NEVER overwritten.
 * Re-scaffolding must not destroy a module's context artifact — the same guarantee `init` makes
 * about the hand-authored knowledge_base documents.
 *
 * README.md is written by moduleSummary.js rather than here, so there is exactly one renderer for it
 * (§5.3) and a freshly-scaffolded module's summary is generated by the same code that regenerates it
 * later.
 *
 * @param {string} modulesDir
 * @param {string} slug
 * @param {{now: Date, entry?: object, dryRun?: boolean}} opts
 * @returns {{plan: object, created: boolean, wrote: string[]}}
 */
function scaffoldModule(modulesDir, slug, opts = {}) {
  const { now, dryRun = false } = opts;
  if (!(now instanceof Date) || Number.isNaN(now.getTime())) {
    throw new ModuleScaffoldError('scaffoldModule requires an explicit valid `now` Date.');
  }

  const plan = planScaffold(modulesDir, slug);
  if (dryRun) return { plan, created: false, wrote: [] };

  const registry = readRegistry(modulesDir);
  const entry = opts.entry || findModule(registry, slug);
  if (!entry) {
    throw new ModuleScaffoldError(
      `No module "${slug}" is registered. Register it before scaffolding — a folder on disk with no ` +
      'registry entry is a module nothing can find.'
    );
  }
  if (entry.status === 'Proposed') {
    throw new ModuleScaffoldError(
      `Module "${slug}" is still Proposed. Approve the Stage 1 module decomposition before ` +
      'scaffolding — a scaffolded folder reads as an approved module.'
    );
  }

  const wrote = [];
  for (const dir of plan.createDirs) {
    fs.mkdirSync(dir, { recursive: true });
    wrote.push(dir);
  }

  const stateFile = path.join(plan.moduleDir, 'module.json');
  if (!fs.existsSync(stateFile)) {
    writeJsonAtomic(stateFile, entry);
    wrote.push(stateFile);
  }

  return { plan, created: !plan.exists, wrote };
}

/**
 * Ensures a stage's folder exists, creating it on first write. Called by the stage that owns the
 * folder, so an absent folder keeps meaning "this stage did not run".
 * @param {string} modulesDir
 * @param {string} slug
 * @param {string} stage
 * @returns {string} the absolute stage folder path
 */
function ensureStageFolder(modulesDir, slug, stage) {
  if (!MODULE_STAGES.includes(stage)) {
    throw new ModuleScaffoldError(
      `Unknown module stage "${stage}". Expected one of: ${MODULE_STAGES.join(', ')}.`
    );
  }
  const dir = path.join(modulesDir, slug, stage);
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}

/**
 * The repo-relative path to a module's stage folder, for use in artifact headers and messages.
 * Always forward-slashed: these strings land in Markdown documents that are read on every platform.
 * @param {string} slug
 * @param {string} [stage]
 * @returns {string}
 */
function moduleArtifactPath(slug, stage) {
  const base = `platform_core_data/modules/${slug}`;
  return stage ? `${base}/${stage}` : base;
}

module.exports = {
  EAGER_STAGE_FOLDERS,
  ModuleScaffoldError,
  planScaffold,
  scaffoldModule,
  ensureStageFolder,
  moduleArtifactPath,
};
